//   UltraMax 400: Kodak E-7023 KODAK ULTRA MAX 400 Film, rev. 2/16, p.4, chart E7023C
//     https://kodakprofessional.com/sites/default/files/wysiwyg/pro/resources/E7023_max_400.pdf
//   Gold 200: Kodak E-7022 KODAK GOLD 200 Film, rev. 06-23, p.4
//     https://www.kodakprofessional.com/sites/default/files/wysiwyg/pro/resources/E7022%20Gold%20tech%20sheet.pdf
//
// IMPORTANT: unlike H-1-5219, these four datasheets publish only the TOTAL
// diffuse spectral density of a midscale neutral and of D-min (400-700 nm),
// not separate yellow/magenta/cyan curves. The tables below are therefore
// an ESTIMATE: the chart was digitised (2 nm grid, tools/digitize*.py) and
// the net density (neutral - D-min) fitted (tools/fitdyes.py, rms 0.011-
// 0.013 D) as the 5219 dye shapes with a per-dye peak shift and width
// scale, minus the masking-coupler consumption (shapes of the D-min bands).
// Fitted shift / width per dye (Y, M, C):
//   Ektar 100:    Y +2.0 nm x0.90, M +3.1 nm x0.99, C +11.3 nm x0.99 (rms 0.013 D)
//   Portra 400:   Y +3.5 nm x0.92, M +3.0 nm x0.96, C +11.7 nm x0.97 (rms 0.012 D)
//   UltraMax 400: Y +3.4 nm x0.91, M +1.3 nm x0.93, C +11.0 nm x0.99 (rms 0.012 D)
//   Gold 200:     Y +2.6 nm x0.90, M +2.9 nm x0.96, C +10.0 nm x0.98 (rms 0.011 D)
// The decomposition is not unique, and above 700 nm (cyan peak) the curve is
// the shifted 5219 shape, not data. Values are peak-normalised (peak 1),
// sampled 400..800 nm every 5 nm.

// DyeSet is one film stock's image-dye curves.
type DyeSet struct {
	Name, Source string
	Y, M, C      SpectralCurve
}

